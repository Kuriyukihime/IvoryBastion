# Builds README.md, the GitHub front page, from media/README.template.md plus the
# package README and changelog that ship in the ZIP, so the two never drift apart.
$ErrorActionPreference='Stop'
$root=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$read={param($path)[IO.File]::ReadAllText((Join-Path $root $path)).Replace("`r`n","`n")}
$template=& $read 'media/README.template.md'
foreach($slot in '<!-- description -->','<!-- changelog -->'){if(-not $template.Contains($slot)){throw ('media/README.template.md is missing '+$slot)}}
# The template has its own header, so drop the package title and the Thunderstore "moved to GitHub" notice.
$description=((& $read 'package/README.md') -replace '\A#[^\n]*\n+','' -replace '(?m)^> \*\*[^\n]*moved to GitHub[^\n]*\n+','').Trim()
if(-not $description){throw 'package/README.md has no description.'}
$versions=foreach($section in [regex]::Split((& $read 'package/CHANGELOG.md'),'(?m)^#{1,2}[ \t]+(?=\d+\.\d+\.\d+)')){
    if(-not $section.Trim()){continue}
    $title,$body=$section.Trim() -split "\n",2
    # Subheadings inside a version sit below its ### title.
    '### '+$title.Trim()+"`n`n"+(($body+'') -replace '(?m)^#{1,3}[ \t]+','#### ').Trim()
}
$changelog=$versions[0]
if($versions.Count -gt 1){$changelog+="`n`n<details>`n<summary>Earlier versions</summary>`n`n"+($versions[1..($versions.Count-1)] -join "`n`n")+"`n`n</details>"}
$readme='<!-- Generated by scripts/github_readme.ps1 from media/README.template.md, package/README.md and package/CHANGELOG.md. Edit those instead. -->'+"`n"+
    $template.Replace('<!-- description -->',$description).Replace('<!-- changelog -->',$changelog).TrimEnd()+"`n"
[IO.File]::WriteAllText((Join-Path $root 'README.md'),$readme,(New-Object Text.UTF8Encoding($false)))
